export interface StripSlot {
  id: string;
  x: number;
  y: number;
  width: number;
  height: number;
  rotation: number; // in degrees
  borderRadius?: number;
  borderColor?: string;
  borderWidth?: number;
}

export interface StripSticker {
  id: string;
  url: string;
  x: number;
  y: number;
  width: number;
  height: number;
  rotation: number; // in degrees
}

export interface StripTextBlock {
  id: string;
  x: number;
  y: number;
  width: number;
  height: number;
  rotation: number; // in degrees
  fontFamily: string;
  fontSize: number;
  fontWeight: number | string;
  color: string;
  align: 'left' | 'center' | 'right';
  binding: 'event.name' | 'event.tagline' | 'event.date' | 'event.venue' | 'event.hashtag' | 'custom';
  text?: string;
  uppercase?: boolean;
}

